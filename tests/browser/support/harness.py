"""Disposable Playwright server/fixture driver. Never defaults to production data.

The Node fixture creates a random-token marker in a fresh temporary directory.
Every operation requires that marker and token. This module is not part of the
application routes or the student archive.
"""
import argparse
import json
import os
from pathlib import Path
import signal
import sys
import threading
import time

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

PASSWORD = 'PlaywrightFixtureOnly!234'


def guarded_directory(value):
    directory = Path(value).resolve()
    token = os.environ.get('ARENA_TEST_TOKEN', '')
    marker = directory / '.playwright-test-data'
    if not token or not directory.name.startswith('arena-pw-') or not marker.is_file() or marker.read_text() != token:
        raise RuntimeError('Refusing to access a directory without the disposable Playwright marker')
    return directory


def seed(db):
    from arena.service import Service
    service = Service(db)
    for username, name, role in [('admin','مدیر آزمایش','admin'),('alpha','تیم آلفا','team'),('beta','تیم بتا','team'),('gamma','تیم گاما','team'),('empty','تیم تازه‌وارد','team')]:
        row = db.one('SELECT id FROM users WHERE username=?', (username,))
        uid = row['id'] if row else db.add_user(username, name, PASSWORD, role)
        if username in ('alpha','beta','gamma') and not db.latest(uid):
            service.submit({'id':uid}, {'source':(ROOT/'B.py').read_text(), 'language':'python', 'filename':'starter.py'})


def state(db, body):
    action = body.get('action')
    user = db.one('SELECT id FROM users WHERE username=?', (body.get('username','alpha'),))
    uid = user['id'] if user else None
    if action == 'expire_sessions':
        with db.transaction() as con:con.execute('UPDATE sessions SET expires=0 WHERE user_id=?', (uid,))
    elif action == 'expire_invite':
        with db.transaction() as con:con.execute('UPDATE invitations SET expires=0 WHERE id=?', (body['id'],))
    elif action == 'missing_code':
        with db.transaction() as con:con.execute('UPDATE users SET active_submission_id=NULL WHERE id=?', (uid,))
    elif action == 'failed_job':
        from arena.service import Service
        service = Service(db)
        jid = service.create_practice({'id':uid}, {'bot':'greedy'})['id']
        with db.transaction() as con:con.execute("UPDATE jobs SET status='failed',error='خطای زیرساخت آزمایشی',finished=? WHERE id=?", (time.time(),jid))
        return {'id':jid}
    elif action == 'completed_jobs':
        # Real, valid replay content generated by the rules; no source is exposed.
        from runner.game import simulate
        count = body.get('count',30)
        if type(count) is not int or not 1 <= count <= 1001:raise ValueError('Fixture count out of bounds')
        submission = db.active_submission(uid)
        for i in range(count):
            log = simulate(i,[lambda *_:0]*2,['تیم آلفا','حریف آزمایشی'])
            when = time.time()-float(body.get('age_seconds',120))
            with db.transaction() as con:
                jid = con.execute("INSERT INTO jobs(kind,status,owner_id,p0,s0,bot,seed,winner,reason,score0,score1,created,finished) VALUES('bot','completed',?,?,?,'greedy',?,?,'completed',?,?,?,?)",
                    (uid,uid,submission['id'] if submission else None,i,log['result']['winner'],log['result']['scores'][0]['total'],log['result']['scores'][1]['total'],when,when)).lastrowid
                log['match_id']=jid
                path=db.directory/'replays'/f'{jid}.json';path.write_text(json.dumps(log,ensure_ascii=False))
                con.execute('UPDATE jobs SET replay=? WHERE id=?',(str(path),jid))
    elif action == 'submission_history':
        count = body.get('count',30)
        if type(count) is not int or not 1 <= count <= 101:raise ValueError('Fixture count out of bounds')
        source = db.latest(uid)
        with db.transaction() as con:
            con.executemany("INSERT INTO submissions(user_id,filename,language,digest,path,kind,created) VALUES(?,'history.py','python',?,?,'official',?)",
                [(uid,source['digest'],source['path'],time.time()-120)]*count)
    elif action == 'storage_full':
        with db.transaction() as con:con.execute('UPDATE submissions SET size_bytes=? WHERE user_id=?',(129*1024**2,uid))
    elif action == 'rename_admin':
        with db.transaction() as con:con.execute("UPDATE users SET username='organizer' WHERE role='admin'")
    elif action == 'disable_admin':
        with db.transaction() as con:con.execute("UPDATE users SET active=0 WHERE role='admin'")
    elif action == 'tournament_failure':
        with db.transaction() as con:
            con.execute("UPDATE jobs SET status='failed',error='خطای زیرساخت آزمایشی' WHERE tournament_id=?",(body['id'],))
            con.execute("UPDATE tournaments SET status='failed' WHERE id=?",(body['id'],))
    else:raise ValueError('Unknown fixture action')
    return {'ok':True}


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('command',choices=['serve','state'])
    parser.add_argument('--data',required=True)
    parser.add_argument('--port',type=int,default=0)
    args=parser.parse_args()
    directory=guarded_directory(args.data)
    # Do not inherit a developer's production origin/proxy/cookie settings.
    os.environ['ARENA_DATA']=str(directory)
    os.environ.pop('ARENA_ORIGIN',None)
    os.environ['ARENA_SECURE_COOKIE']='0'
    os.environ['ARENA_TRUSTED_PROXIES']=''
    from arena.storage import Database
    db=Database(directory)
    if args.command=='state':
        print(json.dumps(state(db,json.load(sys.stdin)),ensure_ascii=False));return
    seed(db)
    from arena.service import Service
    from arena.server import ArenaHTTPServer
    from arena.worker import run_worker
    stop=threading.Event()
    server=ArenaHTTPServer(('127.0.0.1',args.port),Service(db))
    worker=threading.Thread(target=run_worker,args=(db,2,stop),daemon=True);worker.start()
    def shutdown(*_):
        stop.set();threading.Thread(target=server.shutdown,daemon=True).start()
    for sig in (signal.SIGINT,signal.SIGTERM):signal.signal(sig,shutdown)
    print(json.dumps({'ready':True,'url':f'http://127.0.0.1:{server.server_port}'}),flush=True)
    try:server.serve_forever(poll_interval=.05)
    finally:server.server_close();stop.set();worker.join(timeout=35)


if __name__=='__main__':main()
